"""Export lifecycle: request → background build → stored file → short-lived signed link.

- Every export is generated by the worker (202 + job, SPEC §6) and stored under a
  tenant-prefixed key; the API never serves a file without re-checking authorisation.
- Download links are HMAC-signed, bound to the export, user and tenant, and expire in
  ``LINK_TTL_SECONDS`` (≤ 15 min, SPEC §7). Files themselves expire (24 h for full data
  exports [PROPOSED DEFAULT], 7 days for other exports) and a daily job deletes them.
"""

from __future__ import annotations

import io
import tempfile
import uuid
import zipfile
from datetime import datetime, timedelta
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.clock import utcnow
from app.core.errors import AppError, conflict, not_found
from app.core.security import sign, unsign
from app.core.storage import get_storage, new_key
from app.db.models.exports import Export, ExportKind, ExportStatus
from app.db.models.identity import Tenant
from app.exports import reports
from app.exports.writers import to_csv, to_pdf, to_xlsx
from app.services.audit import record
from app.services.notifications import notify
from app.workers.jobs import JobContext, enqueue, handler

LINK_TTL_SECONDS = 15 * 60
FULL_EXPORT_TTL = timedelta(hours=24)
REPORT_TTL = timedelta(days=7)
CONTENT_TYPES = {
    "csv": "text/csv; charset=utf-8",
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "pdf": "application/pdf",
    "zip": "application/zip",
}


def _tenant(db: Session, tenant_id: uuid.UUID) -> Tenant:
    tenant = db.get(Tenant, tenant_id)
    assert tenant is not None
    return tenant


def get(db: Session, tenant_id: uuid.UUID, export_id: uuid.UUID) -> Export:
    e = db.execute(
        select(Export).where(Export.id == export_id, Export.tenant_id == tenant_id)
    ).scalar_one_or_none()
    if e is None:
        raise not_found("Export")
    return e


def history(
    db: Session, tenant_id: uuid.UUID, user_id: uuid.UUID, include_all: bool, limit: int = 100
) -> list[Export]:
    q = select(Export).where(Export.tenant_id == tenant_id)
    if not include_all:
        q = q.where(Export.requested_by == user_id)
    return list(db.execute(q.order_by(Export.created_at.desc()).limit(limit)).scalars())


def _queue(db: Session, ctx: Any, export: Export) -> Export:
    db.add(export)
    db.flush()
    job = enqueue(
        db,
        tenant_id=ctx.tenant_uuid,
        job_type="build_export",
        payload={"export_id": str(export.id)},
        created_by=ctx.user.id,
        max_attempts=2,
    )
    export.job_id = job.id
    record(
        db,
        tenant_id=ctx.tenant_uuid,
        actor=ctx.actor,
        action="export.requested",
        object_type="export",
        object_id=export.id,
        summary={
            "kind": export.kind,
            "report": export.report,
            "format": export.format,
            "params": export.params,
        },
    )
    return export


def request_report(db: Session, ctx: Any, report: str, fmt: str, params: dict[str, Any]) -> Export:
    definition = reports.REPORTS.get(report)
    if definition is None:
        raise not_found("Report")
    if fmt == "pdf" and not definition.pdf:
        raise AppError(
            422, "FORMAT_UNAVAILABLE", "PDF not available", "This report exports as CSV or XLSX."
        )
    parsed = reports.ReportParams.parse(params)
    if definition.requires_supplier and parsed.supplier_id is None:
        raise AppError(
            422, "SUPPLIER_REQUIRED", "Choose a supplier", "This report covers one supplier."
        )
    return _queue(
        db,
        ctx,
        Export(
            tenant_id=ctx.tenant_uuid,
            kind=ExportKind.REPORT.value,
            report=report,
            format=fmt,
            params=parsed.as_dict(),
            requested_by=ctx.user.id,
        ),
    )


def request_evidence_pack(db: Session, ctx: Any, claim_id: uuid.UUID) -> Export:
    from app.services.claims import get as get_claim

    claim = get_claim(db, ctx.tenant_uuid, claim_id)
    return _queue(
        db,
        ctx,
        Export(
            tenant_id=ctx.tenant_uuid,
            kind=ExportKind.EVIDENCE_PACK.value,
            report="claim",
            format="zip",
            params={"claim_id": str(claim.id)},
            requested_by=ctx.user.id,
        ),
    )


def request_full_export(db: Session, ctx: Any) -> Export:
    running = db.execute(
        select(Export.id).where(
            Export.tenant_id == ctx.tenant_uuid,
            Export.kind == ExportKind.FULL_EXPORT.value,
            Export.status.in_([ExportStatus.QUEUED.value, ExportStatus.RUNNING.value]),
        )
    ).first()
    if running:
        raise conflict("EXPORT_IN_PROGRESS", "A full data export is already being prepared.")
    return _queue(
        db,
        ctx,
        Export(
            tenant_id=ctx.tenant_uuid,
            kind=ExportKind.FULL_EXPORT.value,
            report="all",
            format="zip",
            params={},
            requested_by=ctx.user.id,
        ),
    )


# --------------------------------------------------------------------------- build


@handler("build_export")
def _build(db: Session, job: JobContext) -> dict[str, Any]:
    assert job.tenant_id is not None
    export = get(db, job.tenant_id, uuid.UUID(job.payload["export_id"]))
    if export.status not in (ExportStatus.QUEUED.value, ExportStatus.RUNNING.value):
        return {"status": export.status}
    export.status = ExportStatus.RUNNING.value
    tenant = _tenant(db, job.tenant_id)
    now = utcnow()
    try:
        data, filename, rows = _render(db, tenant, export, now)
    except AppError as exc:
        export.status, export.error, export.finished_at = (
            ExportStatus.FAILED.value,
            exc.detail[:500],
            now,
        )
        return {"status": "failed"}
    key = new_key(tenant.id, "exports")
    with data:  # BytesIO or spooled temp file; closed (and deleted) once stored
        export.size_bytes = get_storage().put(key, data)
    export.storage_key, export.filename, export.row_count = key, filename, rows
    export.status, export.finished_at = ExportStatus.SUCCEEDED.value, utcnow()
    export.expires_at = export.finished_at + (
        FULL_EXPORT_TTL if export.kind == ExportKind.FULL_EXPORT.value else REPORT_TTL
    )
    notify(
        db,
        tenant.id,
        [export.requested_by],
        "export_ready",
        f"Your {_label(export)} is ready",
        f"{filename} is ready to download until {export.expires_at:%Y-%m-%d %H:%M} UTC.",
        link="/app/reports#exports",
    )
    return {"status": "succeeded", "rows": rows}


def _label(export: Export) -> str:
    if export.kind == ExportKind.FULL_EXPORT.value:
        return "full data export"
    if export.kind == ExportKind.EVIDENCE_PACK.value:
        return "claim evidence pack"
    definition = reports.REPORTS.get(export.report)
    return f"{definition.title if definition else 'report'} ({export.format.upper()})"


def _render(db: Session, tenant: Tenant, export: Export, now: datetime) -> tuple[Any, str, int]:
    stamp = now.strftime("%Y%m%d-%H%M")
    if export.kind == ExportKind.REPORT.value:
        table = reports.build(db, tenant, export.report, export.params)
        if export.format == "csv":
            body = to_csv(table)
        elif export.format == "xlsx":
            body = to_xlsx(table)
        else:
            body = to_pdf(table, organization=tenant.name, generated_at=now)
        return (
            io.BytesIO(body),
            f"{export.report.replace('_', '-')}-{stamp}.{export.format}",
            len(table.rows),
        )
    if export.kind == ExportKind.EVIDENCE_PACK.value:
        from app.exports.evidence import build_evidence_pack

        claim_id = uuid.UUID(export.params["claim_id"])
        body, number, rows = build_evidence_pack(db, tenant, claim_id, now)
        return io.BytesIO(body), f"claim-{number}-evidence-{stamp}.zip", rows
    from app.exports.full import build_full_export

    spool = tempfile.SpooledTemporaryFile(max_size=32 * 1024 * 1024)  # noqa: SIM115 - closed by _build after upload
    rows = build_full_export(db, tenant, spool)
    spool.seek(0)
    return spool, f"rebateledger-data-{stamp}.zip", rows


# --------------------------------------------------------------------------- download


def issue_link(db: Session, ctx: Any, export_id: uuid.UUID) -> tuple[str, datetime]:
    export = get(db, ctx.tenant_uuid, export_id)
    _check_downloadable(export, ctx)
    token = sign(
        "export-download",
        {"e": str(export.id), "u": str(ctx.user.id), "t": str(ctx.tenant_uuid)},
        LINK_TTL_SECONDS,
    )
    return f"/api/v1/exports/download?token={token}", utcnow() + timedelta(seconds=LINK_TTL_SECONDS)


def check_visible(export: Export, ctx: Any) -> None:
    """Your own exports only, unless you hold full-export rights (404, never 403)."""
    from app.core.permissions import Permission

    if ctx.can(Permission.FULL_EXPORT):
        return
    if export.requested_by != ctx.user.id or export.kind == ExportKind.FULL_EXPORT.value:
        raise not_found("Export")


def _check_downloadable(export: Export, ctx: Any) -> None:
    check_visible(export, ctx)
    if (
        export.status == ExportStatus.SUCCEEDED.value
        and export.expires_at
        and export.expires_at <= utcnow()
    ):
        export.status = ExportStatus.EXPIRED.value
    if export.status != ExportStatus.SUCCEEDED.value or not export.storage_key:
        raise conflict("EXPORT_NOT_READY", "This export is not available for download.")


def open_download(db: Session, ctx: Any, token: str) -> tuple[Export, Any]:
    data = unsign("export-download", token)
    if data is None or data.get("u") != str(ctx.user.id) or data.get("t") != str(ctx.tenant_uuid):
        raise AppError(
            403, "LINK_INVALID", "Link expired", "This download link has expired. Create a new one."
        )
    export = get(db, ctx.tenant_uuid, uuid.UUID(data["e"]))
    _check_downloadable(export, ctx)
    assert export.storage_key is not None
    record(
        db,
        tenant_id=ctx.tenant_uuid,
        actor=ctx.actor,
        action="export.downloaded",
        object_type="export",
        object_id=export.id,
        summary={"kind": export.kind, "format": export.format},
    )
    return export, get_storage().open(export.storage_key)


@handler("expire_exports")
def _expire(db: Session, job: JobContext) -> dict[str, Any]:
    """Daily: delete expired export files (rows stay as history)."""
    now = utcnow()
    expired = list(
        db.execute(
            select(Export).where(
                Export.tenant_id == job.tenant_id,
                Export.status == ExportStatus.SUCCEEDED.value,
                Export.expires_at <= now,
            )
        ).scalars()
    )
    storage = get_storage()
    for e in expired:
        if e.storage_key:
            storage.delete(e.storage_key)
        e.status, e.storage_key = ExportStatus.EXPIRED.value, None
    return {"expired": len(expired)}


def zip_bytes(files: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, content in files.items():
            z.writestr(name, content)
    return buf.getvalue()
